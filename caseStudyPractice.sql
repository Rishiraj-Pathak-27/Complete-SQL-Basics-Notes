## Q1. Find all customers who registered in 2024.

SELECT customer_name
FROM customers 
WHERE signup_date LIKE '2024%';

## Q2. Display all orders whose value exceeds 5000.

SELECT *
FROM orders
WHERE order_value > 5000;

## Q3. Find drivers working in Mumbai.

