FROM drivers
WHERE city = "Mumbai";

## Q4. Count total orders placed.

SELECT COUNT(*) AS total_count
FROM orders;

## Q5. Find average order value.

SELECT AVG(order_value) AS order_value
FROM orders;

## Q6. Show customer names along with their orders.

SELECT c.customer_name AS cust_name, o.order_id AS order_id, o.order_date AS order_date, o.order_value AS order_value
FROM customers c
LEFT JOIN orders o
ON c.customer_id = o.customer_id
ORDER BY order_id ASC;

## Q7. Find total revenue generated by each city.

DESCRIBE orders;
DESCRIBE customers;

SELECT c.city AS city, SUM(o.order_value) AS order_value
FROM customers c
LEFT JOIN orders o
ON c.customer_id = o.customer_id
GROUP BY c.city;

## Q8. Find drivers who delivered more than one order.

DESCRIBE drivers;
DESCRIBE deliveries;

SELECT d1.driver_id AS driver_id, d1.driver_name AS driver_name, COUNT(d2.delivery_id) AS total_deliveries
FROM drivers d1
LEFT JOIN deliveries d2
ON d1.driver_id = d2.driver_id
GROUP BY d1.driver_id, d1.driver_name
HAVING COUNT(*) > 1
ORDER BY total_deliveries ASC;

## Q9. Find warehouses that processed orders worth more than Rs.10000.

DESCRIBE warehouses;
DESCRIBE orders;

SELECT w.warehouse_id AS warehouse_id, w.warehouse_name AS warehouse_name, SUM(o.order_value) as order_value
FROM warehouses w
JOIN orders o
ON w.warehouse_id = o.warehouse_id
GROUP BY warehouse_id, warehouse_name
HAVING SUM(o.order_value) > 10000;

## Q10. Show top 3 customers by total spending.

DESCRIBE customers;

SELECT c.customer_name AS customer_name, SUM(o.order_value) AS order_value
FROM customers c
JOIN orders o
ON c.customer_id = o.customer_id
GROUP BY customer_name
ORDER BY order_value DESC
LIMIT 3;

## Q11. Find customers who placed orders in at least two different months.

DESCRIBE customers;
