## Q12. Find the driver with the lowest average delivery time.

DESCRIBE drivers;
DESCRIBE deliveries;

SELECT d1.driver_id AS driver_id, d1.driver_name AS driver_name, AVG(d2.delivery_time_hours) AS lowest_avg_delivery_time
FROM drivers d1
JOIN deliveries d2
ON d1.driver_id = d2.driver_id
GROUP BY d1.driver_id, d1.driver_name
ORDER BY lowest_avg_delivery_time ASC
LIMIT 1;

